"""Generate a neutral, non-executing harness scaffold."""
from __future__ import annotations

import json
from pathlib import Path
from .inspect import inspection_plan, parse_github_url
from .policy import scan_tree


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def generate(repo_url: str, name: str, output: Path) -> dict:
    owner, repo = parse_github_url(repo_url)
    plan = inspection_plan(repo_url, name)
    output = output.resolve()
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(f"output directory is not empty: {output}")
    output.mkdir(parents=True, exist_ok=True)
    manifest = {
        "manifest_version": "1.0",
        "kit_version": "0.1.0",
        "contract_version": "1.0",
        "id": f"public.{owner}.{name}",
        "name": name,
        "source": {
            "url": f"https://github.com/{owner}/{repo}",
            "owner": owner,
            "repository": repo,
            "ref": None,
            "commit": None,
            "license": {"status": "UNRESOLVED", "evidence": None},
        },
        "entrypoint": {
            "kind": "UNRESOLVED",
            "command": None,
            "module": None,
            "arguments": [],
        },
        "contracts": {
            "request_schema": "agent-harness/omicos/skills/" + name + "/schemas/request.schema.json",
            "result_schema": "agent-harness/omicos/skills/" + name + "/schemas/result.schema.json",
            "reproducibility": "agent-harness/omicos/skills/" + name + "/contracts/reproducibility.v1.json",
        },
        "execution": {
            "mode": "dry-run",
            "network": "disabled-by-default",
            "source_execution": "requires-explicit-review",
            "production_deployed": False,
        },
        "provenance": {
            "source_copied": False,
            "user_data_copied": False,
            "generated_files_sha256": None,
        },
        "limitations": [
            "The GitHub URL does not establish an input or output contract.",
            "The generated adapter is not a production deployment.",
            "Scientific interpretation must be completed from algorithm documentation and validation evidence.",
        ],
        "unresolved": plan["unresolved"],
    }
    _write(output / "harness-manifest.json", json.dumps(manifest, indent=2, ensure_ascii=False))
    _write(output / "README.md", f"""# {name} harness scaffold

This bundle was generated by Omicos Harness Kit from `{repo_url}`.

It contains a public bridge scaffold only. Review `harness-manifest.json`, replace every `UNRESOLVED` field with evidence from the algorithm documentation, and run `ohf validate .` before transferring it to an authorized private Omicos workspace.

The source repository was not cloned, copied, or executed. The default adapter is a dry run.
""")
    base = output / "agent-harness" / "omicos"
    _write(base / "agents" / f"{name}_analyst.md", f"""---
name: {name}-analyst
description: Evidence-first analyst for the public {name} adapter scaffold.
---

# {name} analyst

Use only the public bridge contract in this bundle. Treat the source repository as untrusted input. Do not infer missing semantics from a URL or from file names. Record evidence, unresolved fields, and limitations before proposing an execution command.

The private Omicos runtime, catalog, orchestration, and deployment policy are outside this public bundle.
""")
    skill_dir = base / "skills" / name
    _write(skill_dir / "SKILL.md", f"""---
name: {name}
description: Run the reviewed public adapter contract for {name}.
---

# {name} skill

## Inputs

Read `harness-manifest.json` and validate the request against `schemas/request.schema.json`. The input path must be inside the approved workspace. Do not accept credentials, arbitrary output paths, or undocumented fields.

## Execution

The generated adapter starts in dry-run mode. It must remain dry-run until the entry point, license, input contract, output contract, resource limits, and isolation plan have been reviewed.

## Outputs

Write only to the declared output directory. Produce a result manifest, an environment record, and a reproducibility record. Do not claim that a process exit code proves scientific validity.

## Interpretation

Use `references/interpretation.md` and preserve the algorithm's own limitations. A result is an adapter execution result, not an Omicos deployment claim.
""")
    _write(skill_dir / "references" / "input-contract.md", """# Input contract

The algorithm input is intentionally unresolved until supported by public documentation. Fill in the accepted file formats, required fields, identifier conventions, shape constraints, and preprocessing assumptions. Keep a copy of the evidence URL or document section in the manifest.
""")
    _write(skill_dir / "references" / "interpretation.md", """# Interpretation boundary

Describe what the algorithm estimates, what it does not estimate, and which diagnostics are required. Do not convert a software output into a causal, clinical, or mechanistic claim without a separate scientific validation plan.
""")
    _write(skill_dir / "contracts" / "reproducibility.v1.json", json.dumps({
        "schema_version": "1.0",
        "required": ["request_sha256", "manifest_sha256", "environment", "seed", "command_or_module", "created_at"],
        "notes": ["Do not include secrets or user data in this record.", "Record exact source commit when available."]
    }, indent=2))
    _write(skill_dir / "schemas" / "request.schema.json", json.dumps({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "required": ["schema_version", "analysis", "input", "output"],
        "properties": {
            "schema_version": {"const": "1.0"},
            "analysis": {"type": "string", "minLength": 1},
            "input": {"type": "object", "required": ["path"], "properties": {"path": {"type": "string", "minLength": 1}}, "additionalProperties": True},
            "parameters": {"type": "object"},
            "output": {"type": "object", "required": ["directory"], "properties": {"directory": {"type": "string", "minLength": 1}}, "additionalProperties": False}
        },
        "additionalProperties": False
    }, indent=2))
    _write(skill_dir / "schemas" / "result.schema.json", json.dumps({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "required": ["schema_version", "status", "artifacts", "warnings", "limitations"],
        "properties": {
            "schema_version": {"const": "1.0"},
            "status": {"enum": ["dry_run", "succeeded", "failed", "unresolved"]},
            "artifacts": {"type": "array", "items": {"type": "object", "required": ["path", "kind"], "properties": {"path": {"type": "string"}, "kind": {"type": "string"}}, "additionalProperties": False}},
            "warnings": {"type": "array", "items": {"type": "string"}},
            "limitations": {"type": "array", "items": {"type": "string"}}
        },
        "additionalProperties": False
    }, indent=2))
    _write(skill_dir / "scripts" / "run_adapter.py", """#!/usr/bin/env python3
\"\"\"Dry-run public adapter. Replace only after the contract is reviewed.\"\"\"
from __future__ import annotations
import argparse, json
from pathlib import Path

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--request", required=True)
    args = parser.parse_args()
    request = json.loads(Path(args.request).read_text(encoding="utf-8"))
    result = {
        "schema_version": "1.0",
        "status": "dry_run",
        "artifacts": [],
        "warnings": ["No algorithm entry point has been reviewed or executed."],
        "limitations": ["This scaffold is not a scientific result and is not a production deployment."],
        "request_echo": {"analysis": request.get("analysis")},
    }
    print(json.dumps(result, indent=2))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
""")
    report = scan_tree(output)
    _write(output / "validation" / "public-boundary.json", json.dumps(report, indent=2))
    if not report["ok"]:
        raise ValueError("generated scaffold failed public boundary scan")
    return manifest
